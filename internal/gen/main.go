// Command gen turns api/methods.json into tools/zz_generated.go, the table
// of Flickr API methods the tools are registered from.
//
// Run it through go generate (see tools/tools.go).
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"

	"go.ngs.io/flickr-mcp-server/snapshot"
)

func main() {
	in := flag.String("in", "../api/methods.json", "snapshot to read")
	out := flag.String("out", "zz_generated.go", "Go file to write")
	flag.Parse()
	if err := run(*in, *out); err != nil {
		log.Fatal(err)
	}
}

func run(in, out string) error {
	s, err := snapshot.Read(in)
	if err != nil {
		return err
	}
	src, err := render(s)
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o600)
}

func render(s *snapshot.Snapshot) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen from api/methods.json; DO NOT EDIT.\n\n")
	b.WriteString("package tools\n\n")
	fmt.Fprintf(&b, "// snapshotSource is where api/methods.json came from: %q.\n", s.Source)
	fmt.Fprintf(&b, "const snapshotSource = %q\n\n", s.Source)
	b.WriteString("var methods = []Method{\n")
	for _, m := range s.Methods {
		fmt.Fprintf(&b, "\t{\n\t\tName: %q,\n\t\tDescription: %q,\n", m.Name, m.Description)
		fmt.Fprintf(&b, "\t\tNeedsLogin: %t,\n\t\tNeedsSigning: %t,\n\t\tRequiredPerms: %d,\n\t\tPost: %t,\n", m.NeedsLogin, m.NeedsSigning, m.RequiredPerms, m.Post)
		if len(m.Arguments) == 0 {
			b.WriteString("\t\tArguments: nil,\n")
		} else {
			b.WriteString("\t\tArguments: []Argument{\n")
			for _, a := range m.Arguments {
				fmt.Fprintf(&b, "\t\t\t{Name: %q, Optional: %t, Description: %q},\n", a.Name, a.Optional, a.Description)
			}
			b.WriteString("\t\t},\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
