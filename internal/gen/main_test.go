package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"go.ngs.io/flickr-mcp-server/snapshot"
)

func TestRunWritesTheMethodTable(t *testing.T) {
	dir := t.TempDir()
	in := filepath.Join(dir, "methods.json")
	s := &snapshot.Snapshot{Source: "reflection", Methods: []snapshot.Method{
		{Name: "flickr.photos.delete", Description: `Delete a "photo".`, NeedsLogin: true, NeedsSigning: true, RequiredPerms: 3, Post: true,
			Arguments: []snapshot.Argument{{Name: "photo_id", Description: "The id."}}},
		{Name: "flickr.test.echo", Description: "Echo."},
	}}
	if err := s.Write(in); err != nil {
		t.Fatal(err)
	}
	out := filepath.Join(dir, "zz_generated.go")
	if err := run(in, out); err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	src := string(b)
	for _, want := range []string{
		"// Code generated by internal/gen from api/methods.json; DO NOT EDIT.",
		`const snapshotSource = "reflection"`,
		`Name:          "flickr.photos.delete"`,
		`Description:   "Delete a \"photo\".",`,
		`RequiredPerms: 3,`,
		`{Name: "photo_id", Optional: false, Description: "The id."},`,
		`Arguments:     nil,`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("generated code lacks %q", want)
		}
	}
}

func TestRunReportsErrors(t *testing.T) {
	dir := t.TempDir()
	if err := run(filepath.Join(dir, "missing.json"), filepath.Join(dir, "out.go")); err == nil {
		t.Error("a missing snapshot must fail")
	}
	in := filepath.Join(dir, "m.json")
	if err := (&snapshot.Snapshot{Source: "docs"}).Write(in); err != nil {
		t.Fatal(err)
	}
	if err := run(in, filepath.Join(dir, "no", "dir", "out.go")); err == nil {
		t.Error("an unwritable output must fail")
	}
}
